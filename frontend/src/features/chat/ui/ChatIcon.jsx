export function UserAvatar({ name = "" }) {
  const initials = name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0].toUpperCase())
    .join("") || "Y";

  return <span className="profile-avatar">{initials}</span>;
}
